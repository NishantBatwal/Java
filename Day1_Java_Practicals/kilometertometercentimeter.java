public class kilometertometercentimeter {
    public static void main(String[] args) {
        double kilometers = 5.0; 
        double meters = kilometers * 1000; 
        double centimeters = meters * 100; 

        System.out.println(kilometers + " kilometers is equal to " + meters + " meters.");
        System.out.println(kilometers + " kilometers is equal to " + centimeters + " centimeters.");
    }
    
}
